#!/usr/bin/env python3
"""Generate THIRD_PARTY_LICENSES.txt for the PyInstaller standalone binaries.

The npm platform packages (`@omm-hippo/omm-*`) and the Windows portable ZIP
contain a frozen copy of CPython, OpenSSL, and every Python package of the
standalone runtime graph. This script writes one text file with the complete
license texts and NOTICE files of all of them, read from the build
environment itself:

* Python packages: the closure of `requirements-npm-binary.txt` (or
  `requirements-windows-portable.txt` for win32-x64) as installed in the
  running interpreter, minus build tools, plus the build tools whose code is
  embedded (`embedded_build_tools` in `scripts/license_policy.json`). License
  texts come from each distribution's `.dist-info` (PEP 639 `licenses/`
  directory, `License-File`, and LICENSE/COPYING/NOTICE/AUTHORS files).
* CPython: the interpreter's own LICENSE.txt.
* OpenSSL: the vendored `packaging/licenses/OpenSSL-LICENSE.txt`.
* The local browser interface: `omm/web/static/third-party-licenses.txt` from
  the installed omm package (generated by `web-ui/scripts/licenses.mjs`).

A shipped package without a license file fails the build unless
`python.license_texts` in the policy names a vendored text and a reason.

    python scripts/bundled_licenses.py --target linux-x64-gnu --output THIRD_PARTY_LICENSES.txt

The output is deterministic for a given build environment (sorted, LF line
endings, no timestamps).
"""

from __future__ import annotations

import argparse
import importlib.metadata as metadata
import importlib.util
import platform
import re
import ssl
import sys
import sysconfig
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILE_NAME = "THIRD_PARTY_LICENSES.txt"
TITLE = "OMM standalone binary: third-party software licenses"
CPYTHON_MARKER = "== CPython "
OPENSSL_MARKER = "== OpenSSL"
WINDOWS_TARGET = "win32-x64"
REQUIREMENTS = {
    WINDOWS_TARGET: "requirements-windows-portable.txt",
}
DEFAULT_REQUIREMENTS = "requirements-npm-binary.txt"
WEB_LICENSES = Path("web") / "static" / "third-party-licenses.txt"
RULE = "=" * 78
# Files in a .dist-info directory root that carry license or attribution text.
# Everything under the PEP 639 `licenses/` directory is always included.
_LICENSE_NAME = re.compile(r"(?i)^(licen[cs]e|copying|notice|authors|copyright)")
_LICENSE_TEXT_NAME = re.compile(r"(?i)^(licen[cs]e|copying)")


class BundledLicensesError(RuntimeError):
    """Raised when a shipped component's license text cannot be found."""


def _scripts_import(name: str):
    scripts = str(Path(__file__).resolve().parent)
    if scripts not in sys.path:
        sys.path.insert(0, scripts)
    return __import__(name)


def _normalize(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return "\n".join(line.rstrip() for line in text.split("\n")).strip("\n")


def _read_text(path: Path) -> str:
    data = path.read_bytes()
    try:
        return _normalize(data.decode("utf-8-sig"))
    except UnicodeDecodeError:
        return _normalize(data.decode("latin-1"))


# --------------------------------------------------------------------------
# Python packages
# --------------------------------------------------------------------------


def requirements_file(target: str) -> Path:
    return ROOT / REQUIREMENTS.get(target, DEFAULT_REQUIREMENTS)


def _holds(marker, extras: frozenset[str]) -> bool:
    if marker is None:
        return True
    return any(marker.evaluate({"extra": extra}) for extra in sorted(extras) or [""])


def shipped_distributions(requirements: Path, policy: dict) -> dict[str, metadata.Distribution]:
    """Return canonical name -> installed distribution for every package the
    frozen binary embeds, evaluated for the running interpreter."""
    check_licenses = _scripts_import("check_licenses")
    from packaging.requirements import Requirement
    from packaging.utils import canonicalize_name

    roots = [
        requirement
        for requirement in check_licenses._requirement_lines(requirements)
        if canonicalize_name(requirement.name) not in check_licenses.BUILD_TOOL_NAMES
    ]
    found: dict[str, metadata.Distribution] = {}
    expanded: set[tuple[str, frozenset[str]]] = set()
    queue = [(requirement, frozenset[str]()) for requirement in roots]
    while queue:
        requirement, parent_extras = queue.pop()
        if not _holds(requirement.marker, parent_extras):
            continue
        name = canonicalize_name(requirement.name)
        if name in check_licenses.FIRST_PARTY:
            continue
        extras = frozenset(canonicalize_name(extra) for extra in requirement.extras)
        if (name, extras) in expanded:
            continue
        expanded.add((name, extras))
        distribution = found.get(name) or check_licenses._distribution(name)
        if distribution is None:
            raise BundledLicensesError(
                f"{name} is part of the standalone runtime graph but is not installed; "
                f"install {requirements.name} first"
            )
        found[name] = distribution
        for line in distribution.requires or []:
            queue.append((Requirement(line), extras))
    for name in policy["python"].get("embedded_build_tools", {}):
        canonical = canonicalize_name(name)
        distribution = check_licenses._distribution(canonical)
        if distribution is None:
            raise BundledLicensesError(f"embedded build tool {canonical} is not installed")
        found[canonical] = distribution
    return dict(sorted(found.items()))


def _dist_info_files(distribution: metadata.Distribution) -> list:
    """License-ish files in the distribution's own top-level .dist-info: the
    PEP 639 `licenses/` directory, declared `License-File` entries, and
    LICENSE/COPYING/NOTICE/AUTHORS files in the directory root."""
    declared = set(distribution.metadata.get_all("License-File") or [])
    selected = []
    for path in distribution.files or []:
        parts = path.parts
        if len(parts) < 2 or not parts[0].endswith(".dist-info"):
            continue  # also skips vendored dist-info directories deeper in the tree
        inner = "/".join(parts[1:])
        if (
            (parts[1] == "licenses" and len(parts) > 2)
            or inner in declared
            or (len(parts) == 2 and _LICENSE_NAME.match(parts[1]))
        ):
            selected.append(path)
    return sorted(selected, key=lambda path: "/".join(path.parts[1:]).casefold())


def package_license_files(name: str, distribution: metadata.Distribution, policy: dict) -> list[tuple[str, str]]:
    """Return [(label, text)] for one shipped distribution."""
    files = []
    for path in _dist_info_files(distribution):
        located = Path(distribution.locate_file(path))
        files.append(("/".join(path.parts[1:]), _read_text(located)))
    files = [(label, text) for label, text in files if text]
    if any(_LICENSE_TEXT_NAME.match(label.rsplit("/", 1)[-1]) for label, _ in files):
        return files
    override = policy["python"].get("license_texts", {}).get(name)
    if override:
        if not str(override.get("reason", "")).strip():
            raise BundledLicensesError(f"license_texts override for {name} needs a reason")
        vendored = ROOT / override["path"]
        if not vendored.is_file():
            raise BundledLicensesError(f"license_texts override for {name} points to missing {override['path']}")
        return files + [(override["path"], _read_text(vendored))]
    raise BundledLicensesError(
        f"{name} {distribution.version} ships no license file in its .dist-info; vendor the text and "
        "record it under python.license_texts in scripts/license_policy.json with a reason"
    )


# --------------------------------------------------------------------------
# Runtime components
# --------------------------------------------------------------------------


def cpython_license_path() -> Path:
    version = f"python{sys.version_info.major}.{sys.version_info.minor}"
    candidates = [
        Path(sys.base_prefix) / "LICENSE.txt",
        Path(sys.base_prefix) / "LICENSE",
        Path(sysconfig.get_path("stdlib")) / "LICENSE.txt",
        Path(sys.base_prefix) / "lib" / version / "LICENSE.txt",
        Path(sys.base_prefix) / "share" / "doc" / version / "LICENSE",
    ]
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    raise BundledLicensesError(
        "cannot find the build interpreter's CPython LICENSE.txt; looked in "
        + ", ".join(str(candidate) for candidate in candidates)
    )


def _component(policy: dict, component_id: str) -> dict:
    for item in policy.get("bundled_runtime_components", []):
        if item.get("id") == component_id:
            return item
    raise BundledLicensesError(f"bundled_runtime_components has no entry with id {component_id!r}")


def web_licenses_path() -> Path:
    spec = importlib.util.find_spec("omm")
    if spec is None or not spec.submodule_search_locations:
        raise BundledLicensesError("install omm before generating the standalone license file")
    path = Path(list(spec.submodule_search_locations)[0]) / WEB_LICENSES
    if not path.is_file():
        raise BundledLicensesError(f"the installed omm package has no {WEB_LICENSES.as_posix()}")
    return path


# --------------------------------------------------------------------------
# Rendering
# --------------------------------------------------------------------------


def _section(heading: str, details: list[str], files: list[tuple[str, str]]) -> list[str]:
    out = ["", RULE, heading, *details, RULE]
    for label, text in files:
        out += ["", f"--- {label} ---", "", text]
    return out


def generate(target: str, policy: dict | None = None) -> str:
    check_licenses = _scripts_import("check_licenses")
    policy = policy or check_licenses.load_policy()
    distributions = shipped_distributions(requirements_file(target), policy)

    entries = []
    for name, distribution in distributions.items():
        license_text, source = check_licenses.python_license(name, True, policy)
        package = check_licenses.Package(
            ecosystem="python",
            name=name,
            license=license_text,
            license_class=check_licenses.classify(license_text, policy),
            group="shipped",
            component="python",
            source=source,
        )
        check_licenses._apply_policy(package, policy["python"])
        if package.violation:
            raise BundledLicensesError(
                f"{name} is {license_text} ({package.license_class}) with no recorded exception; "
                "run python scripts/check_licenses.py"
            )
        entries.append((name, distribution, license_text, package_license_files(name, distribution, policy)))

    cpython = _component(policy, "cpython")
    openssl = _component(policy, "openssl")
    python_version = platform.python_version()
    cpython_text = _read_text(cpython_license_path())
    openssl_text = _read_text(ROOT / openssl["text"])
    web_text = _read_text(web_licenses_path())

    out = [
        TITLE,
        "=" * len(TITLE),
        "",
        "The `omm` command in this package is a standalone build made with",
        "PyInstaller. omm itself is licensed under the MIT License (see LICENSE).",
        "The build also contains the third-party software listed below. The",
        "complete license texts and notices of each component follow the list.",
        "",
        f"Generated by scripts/bundled_licenses.py for target {target}",
        f"from the build environment (CPython {python_version}).",
        "",
        "Contents",
        "--------",
        f"CPython {python_version}: {cpython['license']}",
        f"OpenSSL: {openssl['license']}",
        *[f"{name} {distribution.version}: {license_text}" for name, distribution, license_text, _ in entries],
        "OMM local browser interface (npm packages): see the last section",
    ]
    out += _section(
        f"{CPYTHON_MARKER}{python_version} ==",
        [f"License: {cpython['license']}", "Source: https://www.python.org/"],
        [("LICENSE.txt", cpython_text)],
    )
    out += _section(
        f"{OPENSSL_MARKER} ==",
        [
            f"License: {openssl['license']}",
            f"Linked by: Python's ssl module ({ssl.OPENSSL_VERSION}) and the cryptography wheel",
            f"Source: {openssl['source']}",
        ],
        [(openssl["text"], openssl_text)],
    )
    for name, distribution, license_text, files in entries:
        out += _section(
            f"== {name} {distribution.version} ==",
            [f"License: {license_text}", f"Source: https://pypi.org/project/{name}/{distribution.version}/"],
            files,
        )
    out += _section(
        "== OMM local browser interface (npm packages) ==",
        ["Source: omm/web/static/third-party-licenses.txt (web-ui/scripts/licenses.mjs)"],
        [("third-party-licenses.txt", web_text)],
    )
    return "\n".join(out) + "\n"


def validate_text(data: bytes) -> None:
    """Structural check shared by the npm and Windows artifact validators."""
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as error:
        raise BundledLicensesError(f"{FILE_NAME} is not UTF-8") from error
    if not text.startswith(TITLE + "\n"):
        raise BundledLicensesError(f"{FILE_NAME} does not start with the generated header")
    if "\r" in text:
        raise BundledLicensesError(f"{FILE_NAME} must use LF line endings")
    for marker in (CPYTHON_MARKER, OPENSSL_MARKER):
        if f"\n{marker}" not in text:
            raise BundledLicensesError(f"{FILE_NAME} has no {marker.strip('= ')} section")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--target", required=True, help="npm target name, e.g. linux-x64-gnu or win32-x64")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        text = generate(args.target)
        validate_text(text.encode("utf-8"))
    except (BundledLicensesError, OSError) as error:
        print(f"third-party license generation failed: {error}", file=sys.stderr)
        return 1
    args.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.output} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
